#!/usr/bin/env bash
# compile-gpugemv-shader.sh — AOT-compile Q4_K GEMV shaders to C headers.
#
# Compiles:
#   shaders/gpugemv_q4k.hlsl        → gpugemv_q4k_dxil.h        (naive, H6.1)
#   shaders/gpugemv_q4k_wave32.hlsl → gpugemv_q4k_wave32_dxil.h (H6.2 LDS-red)
#   shaders/gpugemv_q4k_rows.hlsl   → gpugemv_q4k_rows_dxil.h   (H6.3 multi-row)
#   shaders/gpugemv_q4k_dot4.hlsl   → gpugemv_q4k_dot4_dxil.h   (H6.3 int8 dot, cs_6_4)
#   shaders/ggml_d3d12_mmv_{q4_0,q4_k,q6_k}.hlsl → ggml_d3d12_mmv_*_t{64,128}_dxil.h (cs_6_4)
#     (D2 backend; one blob per thread-group width, -D NUM_THREADS)
#   shaders/ggml_d3d12_get_rows_q6_k.hlsl → ggml_d3d12_get_rows_q6_k_dxil.h (cs_6_4)
#   shaders/ggml_d3d12_add_bias_f32.hlsl → ggml_d3d12_add_bias_f32_dxil.h (cs_6_4,
#     -denorm preserve so the fp32 add matches the CPU bit for bit)
#   shaders/ggml_d3d12_quantize_q8.hlsl → ggml_d3d12_quantize_q8_{0,k}_dxil.h (cs_6_4,
#     -denorm preserve; -D Q8_K=1 for the q8_K blob)
#   shaders/ggml_d3d12_swiglu_f32.hlsl → ggml_d3d12_swiglu_f32_dxil.h (cs_6_4, -denorm preserve)
#     and ggml_d3d12_swiglu_f32_f64_dxil.h (-D FMA_F64=1: fma from doubles, shader doubles)
#   shaders/ggml_d3d12_rmsnorm_probe.hlsl → ggml_d3d12_rmsnorm_probe_dxil.h (cs_6_4,
#     -denorm preserve; selftest cost probe, needs shader doubles; _u16 -D UNROLL=1, _floor -D FLOOR=1)
#   shaders/ggml_d3d12_fma_probe.hlsl → ggml_d3d12_fma_probe_{int,f64,mad}_dxil.h (cs_6_4,
#     -denorm preserve; -D F64=1 / -D MAD=1; selftest cost probe of the fp32 fma emulations)
#
# Usage: compile-gpugemv-shader.sh [naive|wave32|rows|dot4|mmv_q4_0|mmv_q4_k|mmv_q6_k|get_rows_q6_k|add_bias_f32|rope_f32|quantize_q8_0|quantize_q8_k|swiglu_f32|swiglu_f32_f64|rmsnorm_probe|rmsnorm_probe_u16|rmsnorm_probe_floor|fma_probe_{int,f64,mad} ...]
#        (default: all)
# A different dxc release emits different bytes: regenerate only the targets
# you changed so measured blobs stay the ones the CSVs were recorded with.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DXC="${DXC:-dxc}"

if [[ ! -x "$DXC" ]] && ! command -v "$DXC" >/dev/null 2>&1; then
	echo "dxc not found (set DXC=...). Example Linux release:" >&2
	echo "  https://github.com/microsoft/DirectXShaderCompiler/releases" >&2
	echo "  pacman extra/directx-shader-compiler (do not install AUR packages)" >&2
	exit 1
fi

emit_header() {
	local dxil="$1"
	local out_h="$2"
	local source_rel="$3"
	local symbol="$4"
	local profile="$5"
	python3 - "$dxil" "$out_h" "$source_rel" "$symbol" "$profile" <<'PY'
import sys
from pathlib import Path

data = Path(sys.argv[1]).read_bytes()
out = Path(sys.argv[2])
source = sys.argv[3]
symbol = sys.argv[4]
profile = sys.argv[5]
out.parent.mkdir(parents=True, exist_ok=True)
lines = [
    "// AUTO-GENERATED by scripts/compile-gpugemv-shader.sh — do not edit.",
    f"// Source: {source} ({profile} CSMain)",
    "#pragma once",
    "#include <cstddef>",
    "#include <cstdint>",
    f"// {len(data)} bytes DXIL",
    "// clang-format off",
    f"static const uint8_t {symbol}[] = {{",
]
for i in range(0, len(data), 12):
    chunk = data[i : i + 12]
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
lines.append("};")
lines.append(f"static const size_t {symbol}Size = {len(data)};")
lines.append("// clang-format on")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({len(data)} bytes)")
PY
}

compile_one() {
	local hlsl="$1"
	local out_h="$2"
	local source_rel="$3"
	local symbol="$4"
	local profile="$5"
	shift 5
	local tmp
	tmp="$(mktemp)"
	"$DXC" -T "$profile" -E CSMain "$@" -Fo "$tmp" "$hlsl"
	emit_header "$tmp" "$out_h" "$source_rel" "$symbol" "$profile"
	rm -f "$tmp"
}

compile_target() {
	case "$1" in
	naive) compile_one "$ROOT/shaders/gpugemv_q4k.hlsl" \
		"$ROOT/shaders/generated/gpugemv_q4k_dxil.h" \
		"shaders/gpugemv_q4k.hlsl" "kGpugemvQ4kDxil" cs_6_0 ;;
	wave32) compile_one "$ROOT/shaders/gpugemv_q4k_wave32.hlsl" \
		"$ROOT/shaders/generated/gpugemv_q4k_wave32_dxil.h" \
		"shaders/gpugemv_q4k_wave32.hlsl" "kGpugemvQ4kWave32Dxil" cs_6_0 ;;
	rows) compile_one "$ROOT/shaders/gpugemv_q4k_rows.hlsl" \
		"$ROOT/shaders/generated/gpugemv_q4k_rows_dxil.h" \
		"shaders/gpugemv_q4k_rows.hlsl" "kGpugemvQ4kRowsDxil" cs_6_0 ;;
	dot4) compile_one "$ROOT/shaders/gpugemv_q4k_dot4.hlsl" \
		"$ROOT/shaders/generated/gpugemv_q4k_dot4_dxil.h" \
		"shaders/gpugemv_q4k_dot4.hlsl" "kGpugemvQ4kDot4Dxil" cs_6_4 ;;
	mmv_q4_0 | mmv_q4_k | mmv_q6_k)
		local t="${1#mmv_}" w sym
		for w in 64 128; do
			sym="kGgmlD3d12Mmv$(echo "$t" | sed -e 's/_\(.\)/\U\1/g' -e 's/^./\U&/')T${w}Dxil"
			compile_one "$ROOT/shaders/ggml_d3d12_mmv_${t}.hlsl" \
				"$ROOT/shaders/generated/ggml_d3d12_mmv_${t}_t${w}_dxil.h" \
				"shaders/ggml_d3d12_mmv_${t}.hlsl -D NUM_THREADS=${w}" "$sym" cs_6_4 \
				-D "NUM_THREADS=${w}"
		done
		;;
	get_rows_q6_k) compile_one "$ROOT/shaders/ggml_d3d12_get_rows_q6_k.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_get_rows_q6_k_dxil.h" \
		"shaders/ggml_d3d12_get_rows_q6_k.hlsl" "kGgmlD3d12GetRowsQ6KDxil" cs_6_4 ;;
	add_bias_f32) compile_one "$ROOT/shaders/ggml_d3d12_add_bias_f32.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_add_bias_f32_dxil.h" \
		"shaders/ggml_d3d12_add_bias_f32.hlsl -denorm preserve" "kGgmlD3d12AddBiasF32Dxil" \
		cs_6_4 -denorm preserve ;;
	rope_f32) compile_one "$ROOT/shaders/ggml_d3d12_rope_f32.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_rope_f32_dxil.h" \
		"shaders/ggml_d3d12_rope_f32.hlsl -denorm preserve" "kGgmlD3d12RopeF32Dxil" \
		cs_6_4 -denorm preserve ;;
	quantize_q8_0) compile_one "$ROOT/shaders/ggml_d3d12_quantize_q8.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_quantize_q8_0_dxil.h" \
		"shaders/ggml_d3d12_quantize_q8.hlsl -denorm preserve" "kGgmlD3d12QuantizeQ80Dxil" \
		cs_6_4 -denorm preserve ;;
	quantize_q8_k) compile_one "$ROOT/shaders/ggml_d3d12_quantize_q8.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_quantize_q8_k_dxil.h" \
		"shaders/ggml_d3d12_quantize_q8.hlsl -D Q8_K=1 -denorm preserve" "kGgmlD3d12QuantizeQ8KDxil" \
		cs_6_4 -D Q8_K=1 -denorm preserve ;;
	swiglu_f32) compile_one "$ROOT/shaders/ggml_d3d12_swiglu_f32.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_swiglu_f32_dxil.h" \
		"shaders/ggml_d3d12_swiglu_f32.hlsl -denorm preserve" "kGgmlD3d12SwigluF32Dxil" \
		cs_6_4 -denorm preserve ;;
	swiglu_f32_f64) compile_one "$ROOT/shaders/ggml_d3d12_swiglu_f32.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_swiglu_f32_f64_dxil.h" \
		"shaders/ggml_d3d12_swiglu_f32.hlsl -D FMA_F64=1 -denorm preserve" "kGgmlD3d12SwigluF32F64Dxil" \
		cs_6_4 -D FMA_F64=1 -denorm preserve ;;
	rmsnorm_probe) compile_one "$ROOT/shaders/ggml_d3d12_rmsnorm_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_rmsnorm_probe_dxil.h" \
		"shaders/ggml_d3d12_rmsnorm_probe.hlsl -denorm preserve" "kGgmlD3d12RmsnormProbeDxil" \
		cs_6_4 -denorm preserve ;;
	rmsnorm_probe_u16) compile_one "$ROOT/shaders/ggml_d3d12_rmsnorm_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_rmsnorm_probe_u16_dxil.h" \
		"shaders/ggml_d3d12_rmsnorm_probe.hlsl -D UNROLL=1 -denorm preserve" "kGgmlD3d12RmsnormProbeU16Dxil" \
		cs_6_4 -D UNROLL=1 -denorm preserve ;;
	fma_probe_int) compile_one "$ROOT/shaders/ggml_d3d12_fma_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_fma_probe_int_dxil.h" \
		"shaders/ggml_d3d12_fma_probe.hlsl -denorm preserve" "kGgmlD3d12FmaProbeIntDxil" \
		cs_6_4 -denorm preserve ;;
	fma_probe_f64) compile_one "$ROOT/shaders/ggml_d3d12_fma_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_fma_probe_f64_dxil.h" \
		"shaders/ggml_d3d12_fma_probe.hlsl -D F64=1 -denorm preserve" "kGgmlD3d12FmaProbeF64Dxil" \
		cs_6_4 -D F64=1 -denorm preserve ;;
	fma_probe_mad) compile_one "$ROOT/shaders/ggml_d3d12_fma_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_fma_probe_mad_dxil.h" \
		"shaders/ggml_d3d12_fma_probe.hlsl -D MAD=1 -denorm preserve" "kGgmlD3d12FmaProbeMadDxil" \
		cs_6_4 -D MAD=1 -denorm preserve ;;
	rmsnorm_probe_floor) compile_one "$ROOT/shaders/ggml_d3d12_rmsnorm_probe.hlsl" \
		"$ROOT/shaders/generated/ggml_d3d12_rmsnorm_probe_floor_dxil.h" \
		"shaders/ggml_d3d12_rmsnorm_probe.hlsl -D FLOOR=1 -denorm preserve" "kGgmlD3d12RmsnormProbeFloorDxil" \
		cs_6_4 -D FLOOR=1 -denorm preserve ;;
	*)
		echo "unknown target: $1 (naive|wave32|rows|dot4|mmv_q4_0|mmv_q4_k|mmv_q6_k|get_rows_q6_k|add_bias_f32|rope_f32|quantize_q8_0|quantize_q8_k|swiglu_f32|swiglu_f32_f64|rmsnorm_probe|rmsnorm_probe_u16|rmsnorm_probe_floor|fma_probe_int|fma_probe_f64|fma_probe_mad)" >&2
		exit 2
		;;
	esac
}

if [[ $# -eq 0 ]]; then
	set -- naive wave32 rows dot4 mmv_q4_0 mmv_q4_k mmv_q6_k get_rows_q6_k add_bias_f32 rope_f32 \
		quantize_q8_0 quantize_q8_k swiglu_f32 swiglu_f32_f64 rmsnorm_probe rmsnorm_probe_u16 rmsnorm_probe_floor \
		fma_probe_int fma_probe_f64 fma_probe_mad
fi
for target in "$@"; do
	compile_target "$target"
done
